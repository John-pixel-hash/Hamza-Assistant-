      array['shopify','wordpress','website','landing page','woocommerce','elementor','theme','hosting','domain','speed','core web vitals']),
    (new.id, 'graphic-design',   'Graphic Design', false,
      array['logo','brand','design','flyer','banner','creative','mockup','revision']),
    (new.id, 'meta-ads',         'Facebook and Instagram Ads', true,
      array['facebook ads','meta','instagram ads','pixel','cpm','cpc','roas','campaign','audience','creative','conversions api']),
    (new.id, 'google-ads',       'Google Ads', true,
      array['google ads','adwords','search ads','keyword','pmax','performance max','quality score','conversion tracking']),
    (new.id, 'marketing-strategy','Digital Marketing Strategy', true,
      array['strategy','funnel','positioning','channel','budget','growth','analytics','marketing plan']),
    (new.id, 'ecommerce',        'Ecommerce and Dropshipping', true,
