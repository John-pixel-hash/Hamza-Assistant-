-- ===========================================================================
-- 15. ROW LEVEL SECURITY
-- Every table. Default deny. Only your user id sees your rows.
-- ===========================================================================
do $$
declare
  t text;
  tables text[] := array[
    'clients','client_facts','threads','messages','attachments','projects',
    'project_questions','project_steps','research_notes','playbooks',
    'model_registry','task_routing','ai_runs','message_embeddings','rate_events'
  ];
begin
  foreach t in array tables loop
    execute format('alter table public.%I enable row level security;', t);
    execute format('alter table public.%I force row level security;', t);
    execute format($f$
      create policy %I on public.%I
        for all
        to authenticated
        using (user_id = auth.uid())
        with check (user_id = auth.uid());
    $f$, t || '_owner_policy', t);
  end loop;
end $$;

alter table public.profiles enable row level security;
alter table public.profiles force row level security;

create policy profiles_owner_policy on public.profiles
  for all to authenticated
  using (id = auth.uid())
  with check (id = auth.uid());

