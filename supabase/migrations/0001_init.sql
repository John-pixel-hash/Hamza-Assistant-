-- ============================================================================
-- Hamza Assistant - Phase 0 schema
-- Postgres 15+ / Supabase. Run in the Supabase SQL editor in order.
--
-- Design notes:
--  * Single user system, but every table still carries user_id and a row level
--    security policy. A bug in the app can never leak or cross contaminate data.
--  * Enumerations are CHECK constraints rather than Postgres enums, so adding a
--    stage or status later is a one line change, not a migration dance.
--  * Money is stored in minor units (kobo, cents) as integers, never floats.
-- ============================================================================

create extension if not exists vector;
create extension if not exists pgcrypto;

-- ---------------------------------------------------------------------------
-- Shared helper: keep updated_at honest
-- ---------------------------------------------------------------------------
create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

-- ===========================================================================
-- 1. PROFILES
-- One row for you. Settings, voice preferences, defaults.
-- ===========================================================================
create table public.profiles (
  id               uuid primary key references auth.users(id) on delete cascade,
  email            text not null,
  display_name     text,
  business_name    text,
  business_summary text,                 -- what you sell, who you sell to. Loaded into every prompt.
  timezone         text not null default 'Africa/Lagos',
  tone_notes       text,                 -- your own words on how you want to sound
  default_provider text not null default 'google',
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);

create trigger profiles_updated_at before update on public.profiles
  for each row execute function public.set_updated_at();

-- ===========================================================================
-- 2. CLIENTS
-- ===========================================================================
create table public.clients (
  id                  uuid primary key default gen_random_uuid(),
  user_id             uuid not null references auth.users(id) on delete cascade,
  name                text not null,
  company             text,
  source              text,              -- fiverr, referral, instagram, cold_email, other
  country             text,
  timezone            text,
  channel             text,              -- preferred channel: fiverr, email, whatsapp, instagram
  stage               text not null default 'lead'
                      check (stage in ('lead','contacted','quoted','negotiating','active','delivered','repeat','lost')),
  deal_value_estimate bigint,            -- minor units
  currency            text default 'USD',
  tags                text[] not null default '{}',
  notes               text,
  -- memory: rolling summary, regenerated by the AI layer
  summary             text,
  summary_updated_at  timestamptz,
  summary_msg_count   integer not null default 0,
  last_contact_at     timestamptz,
  created_at          timestamptz not null default now(),
  updated_at          timestamptz not null default now()
);

create index clients_user_idx        on public.clients (user_id, last_contact_at desc nulls last);
create index clients_stage_idx       on public.clients (user_id, stage);
create index clients_name_search_idx on public.clients using gin (to_tsvector('english', name || ' ' || coalesce(company, '')));

create trigger clients_updated_at before update on public.clients
  for each row execute function public.set_updated_at();

-- ===========================================================================
-- 3. CLIENT FACTS
-- Structured memory. Small, dense, sourced. This is what makes the assistant
-- feel like it remembers, without replaying whole transcripts.
-- ===========================================================================
create table public.client_facts (
  id                uuid primary key default gen_random_uuid(),
  user_id           uuid not null references auth.users(id) on delete cascade,
  client_id         uuid not null references public.clients(id) on delete cascade,
  key               text not null,       -- budget_signal, decision_maker, promise_2026_09_14, objection_type
  value             text not null,
  confidence        numeric(3,2) not null default 0.70 check (confidence between 0 and 1),
  source_message_id uuid,                -- provenance, set after messages exist
  is_pinned         boolean not null default false, -- pinned facts are always injected
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now(),
  unique (client_id, key)
);

create index client_facts_client_idx on public.client_facts (client_id, is_pinned desc);

create trigger client_facts_updated_at before update on public.client_facts
  for each row execute function public.set_updated_at();

-- ===========================================================================
-- 4. THREADS AND MESSAGES
-- ===========================================================================
create table public.threads (
  id             uuid primary key default gen_random_uuid(),
  user_id        uuid not null references auth.users(id) on delete cascade,
  client_id      uuid references public.clients(id) on delete cascade,
  title          text not null,
  mode           text not null default 'client_reply'
                 check (mode in ('client_reply','project','internal')),
  status         text not null default 'open' check (status in ('open','archived')),
  model_override text,                   -- e.g. 'openai:gpt-5.5'. null means use task default.
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);

create index threads_user_idx   on public.threads (user_id, updated_at desc);
create index threads_client_idx on public.threads (client_id, updated_at desc);

create trigger threads_updated_at before update on public.threads
  for each row execute function public.set_updated_at();

create table public.messages (
  id                uuid primary key default gen_random_uuid(),
  user_id           uuid not null references auth.users(id) on delete cascade,
  thread_id         uuid not null references public.threads(id) on delete cascade,
  role              text not null check (role in ('user','assistant','system','tool')),
  content           text not null,
  -- provenance and cost
  provider          text,
  model_id          text,
  input_tokens      integer,
  output_tokens     integer,
  cost_usd          numeric(10,6),
  latency_ms        integer,
  -- what the AI layer did around this message
  research_note_id  uuid,
  guardrail_flags   jsonb not null default '{}'::jsonb, -- {em_dash_removed: n, tone_score: 8, length_ok: true}
  meta              jsonb not null default '{}'::jsonb, -- intent, next_step suggestion, risk flags
  content_tsv       tsvector generated always as (to_tsvector('english', coalesce(content,''))) stored,
  created_at        timestamptz not null default now()
);

create index messages_thread_idx on public.messages (thread_id, created_at);
create index messages_fts_idx    on public.messages using gin (content_tsv);
create index messages_user_idx   on public.messages (user_id, created_at desc);

