-- Client list with activity and open work, for the hub sidebar.
create or replace view public.client_overview
with (security_invoker = true)
as
select
  c.id,
  c.user_id,
  c.name,
  c.company,
  c.stage,
  c.source,
  c.channel,
  c.tags,
  c.deal_value_estimate,
  c.currency,
  c.last_contact_at,
  c.summary,
  (select count(*) from public.projects p
     where p.client_id = c.id and p.status not in ('delivered','cancelled')) as open_projects,
  (select count(*) from public.messages m
     join public.threads t on t.id = m.thread_id
    where t.client_id = c.id and m.role = 'user') as client_message_count
from public.clients c;

-- Unpaid-attention list: who needs a follow up, and how long it has been.
create or replace view public.pending_followups
with (security_invoker = true)
as
select
  c.id as client_id,
  c.user_id,
  c.name,
  c.stage,
  c.last_contact_at,
  now() - c.last_contact_at as since_last_contact,
  case
    when c.last_contact_at is null then 'no_contact_yet'
    when now() - c.last_contact_at > interval '7 days'
         and c.stage in ('quoted','negotiating') then 'follow_up_overdue'
    when now() - c.last_contact_at > interval '3 days'
         and c.stage in ('lead','contacted') then 'nudge'
    else 'ok'
  end as followup_state
from public.clients c
where c.stage not in ('lost','delivered','repeat');

-- Cost dashboard, last 30 days.
create or replace view public.cost_summary
with (security_invoker = true)
as
select
  user_id,
  provider,
  model_id,
  task,
  count(*)                        as runs,
  sum(input_tokens)               as input_tokens,
  sum(output_tokens)              as output_tokens,
  round(sum(cost_usd), 4)         as cost_usd,
  round(avg(latency_ms))          as avg_latency_ms,
  round(avg((guardrail_actions->>'tone_score')::numeric), 1) as avg_tone_score,
  sum(coalesce((guardrail_actions->>'em_dash_removed')::int, 0)) as em_dashes_stopped
from public.ai_runs
where created_at > now() - interval '30 days'
group by user_id, provider, model_id, task;

