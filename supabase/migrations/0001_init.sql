-- Semantic search function, scoped to the calling user by RLS on the table.
create or replace function public.match_messages(
  p_client_id    uuid,
  p_query_vector vector(768),
  p_limit        integer default 8
)
returns table (
  message_id  uuid,
  content     text,
  role        text,
  created_at  timestamptz,
  similarity  float
)
language sql
stable
security invoker
as $$
  select m.id, m.content, m.role, m.created_at,
         1 - (e.embedding <=> p_query_vector) as similarity
  from public.message_embeddings e
  join public.messages m on m.id = e.message_id
  where e.client_id = p_client_id
  order by e.embedding <=> p_query_vector
  limit p_limit;
$$;

